-- 5) App-/Design-Einstellungen
create table if not exists public.app_settings (
  id int primary key default 1 check (id = 1),
  updated_at timestamptz not null default now(),
  app_name text not null default 'Good News',
  logo_url text,
  logo_path text,
  background_color text not null default '#0e0e10',
  text_color text not null default '#f5f5f5',
  accent_color text not null default '#ffffff',
  title_size text not null default 'normal' check (title_size in ('compact','normal','large')),
  corner_style text not null default 'soft' check (corner_style in ('square','soft','round')),
  image_mode text not null default 'full' check (image_mode in ('full','top','hidden')),
  overlay_strength int not null default 65 check (overlay_strength between 0 and 90),
  show_category boolean not null default true,
  show_date boolean not null default true,
  show_sources boolean not null default true,
  show_counter boolean not null default true
);

insert into public.app_settings (id)
values (1)
on conflict (id) do nothing;

alter table public.app_settings enable row level security;

revoke all on table public.app_settings from anon, authenticated;
grant select on table public.app_settings to anon, authenticated;
grant update on table public.app_settings to authenticated;

drop policy if exists "Public reads app settings" on public.app_settings;
create policy "Public reads app settings"
on public.app_settings for select
to anon, authenticated
using (true);

drop policy if exists "Editors update app settings" on public.app_settings;
create policy "Editors update app settings"
on public.app_settings for update
to authenticated
using (id = 1)
with check (id = 1);
