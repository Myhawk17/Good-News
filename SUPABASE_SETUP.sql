create or replace function public.get_analytics_summary()
returns table (
  active_today bigint,
  active_7d bigint,
  active_30d bigint,
  favorites_today bigint,
  favorites_7d bigint,
  favorites_30d bigint,
  shares_today bigint,
  shares_7d bigint,
  shares_30d bigint
)
language sql
stable
security invoker
set search_path = public
as $$
  with bounds as (
    select ((date_trunc('day', now() at time zone 'Europe/Berlin')) at time zone 'Europe/Berlin') as today_start
  )
  select
    count(distinct visitor_id) filter (where event_type='active' and created_at >= b.today_start)::bigint,
    count(distinct visitor_id) filter (where event_type='active' and created_at >= now() - interval '7 days')::bigint,
    count(distinct visitor_id) filter (where event_type='active' and created_at >= now() - interval '30 days')::bigint,
    count(*) filter (where event_type='favorite' and created_at >= b.today_start)::bigint,
    count(*) filter (where event_type='favorite' and created_at >= now() - interval '7 days')::bigint,
    count(*) filter (where event_type='favorite' and created_at >= now() - interval '30 days')::bigint,
    count(*) filter (where event_type='share' and created_at >= b.today_start)::bigint,
    count(*) filter (where event_type='share' and created_at >= now() - interval '7 days')::bigint,
    count(*) filter (where event_type='share' and created_at >= now() - interval '30 days')::bigint
  from public.analytics_events, bounds b
  group by b.today_start;
$$;

revoke all on function public.get_analytics_summary() from public;
grant execute on function public.get_analytics_summary() to authenticated;

