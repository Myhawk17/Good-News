-- GOOD NEWS RELEASE SECURITY – Rollenbasierte Redaktion
-- =========================================================
-- Normale angemeldete Nutzer sind KEINE Redakteure.
-- Nur Nutzer mit role='admin' in public.user_roles erhalten Redaktionsrechte.

create table if not exists public.user_roles (
  user_id uuid primary key references auth.users(id) on delete cascade,
  role text not null check (role in ('admin','user')),
  created_at timestamptz not null default now()
);

alter table public.user_roles enable row level security;

revoke all on table public.user_roles from anon, authenticated;
grant select on table public.user_roles to authenticated;

drop policy if exists "Users read own role" on public.user_roles;
create policy "Users read own role"
on public.user_roles for select
to authenticated
using (auth.uid() = user_id);

create or replace function public.is_admin()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1
    from public.user_roles
    where user_id = auth.uid() and role = 'admin'
  );
$$;

-- SECURITY DEFINER nicht pauschal für PUBLIC ausführbar lassen.
revoke all on function public.is_admin() from public;
grant execute on function public.is_admin() to anon, authenticated;

