-- 1) Tabelle
create table if not exists public.news (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  published_date date not null,
  published_time time not null default '12:00',
  publish_at timestamptz not null default now(),
  category text not null check (char_length(category) <= 40),
  story_key text check (story_key is null or char_length(story_key) <= 80),
  title text not null check (char_length(title) <= 180),
  summary text not null check (char_length(summary) <= 1800),
  context_text text check (context_text is null or char_length(context_text) <= 1400),
  status text not null default 'draft' check (status in ('draft','published')),
  priority text not null default 'normal' check (priority in ('normal','top')),
  priority_rank int not null default 0 check (priority_rank in (0,1)),
  image_url text,
  image_path text,
  image_credit text,
  sources jsonb not null default '[]'::jsonb
);

create index if not exists news_public_feed_idx
on public.news (status, publish_at desc);

create index if not exists news_story_idx
on public.news (story_key);

alter table public.news enable row level security;

